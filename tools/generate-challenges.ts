import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { generateChallenge, PLACE_TITLES, PRACTICE_TARGETS } from '../src/shared/generation.ts';
import type { AuthoredPuzzle } from '../src/shared/types.ts';

const puzzles: AuthoredPuzzle[] = [];
for (const [index, target] of PRACTICE_TARGETS.entries()) {
  const found = generateChallenge({
    id: `routes-${String(index + 1).padStart(2, '0')}`,
    title: PLACE_TITLES[index] ?? 'A village to reconnect',
    minimum: target, seed: 71 * (index + 1), chapter: index + 1,
  });
  puzzles.push(found);
  console.log(`${found.id}: ${found.board.length}x${found.board.length}, ${found.journey?.join(' > ')}, proven minimum ${target}`);
}
if (new Set(puzzles.map((puzzle) => puzzle.board.join('/'))).size !== puzzles.length) {
  throw new Error('Generated challenges contain duplicate terrain. No output was written.');
}
const destination = fileURLToPath(new URL('../src/shared/challenges.generated.ts', import.meta.url));
await writeFile(destination,
  `// Generated by tools/generate-challenges.ts. Minimums are certified, not scramble counts.\n` +
  `import type { AuthoredPuzzle } from './types.ts';\n\n` +
  `export const CHALLENGES: readonly AuthoredPuzzle[] = ${JSON.stringify(puzzles, null, 2)};\n`,
  'utf8');
console.log(`Wrote ${puzzles.length} certified daily challenges.`);
